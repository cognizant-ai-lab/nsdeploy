"""Install and resolve persistent static deployment bundles.

The ordinary ``POST /bundles`` endpoint is intentionally ephemeral.  A static
*deployment* needs the same archive installed below its deployment work directory so
the service can give it a stable URL and put that URL on the map.
"""
from __future__ import annotations

import io
import shutil
import tarfile
import uuid
from pathlib import Path, PurePosixPath


class StaticSiteError(RuntimeError):
    """A generated archive could not be safely installed."""


def install_archive(archive: bytes, target: Path) -> None:
    """Safely unpack ``archive`` and atomically replace ``target``.

    The archive is generated by this process, but it is still treated as untrusted at
    the filesystem boundary: absolute/traversing paths and links are refused.
    """
    target = Path(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    stage = target.parent / f".{target.name}.build-{uuid.uuid4().hex}"
    backup = target.parent / f".{target.name}.previous-{uuid.uuid4().hex}"
    stage.mkdir()
    try:
        with tarfile.open(fileobj=io.BytesIO(archive), mode="r:gz") as packed:
            for member in packed.getmembers():
                relative = PurePosixPath(member.name)
                if (relative.is_absolute() or not relative.parts
                        or any(part in ("", ".", "..") for part in relative.parts)):
                    raise StaticSiteError(f"unsafe path in generated bundle: {member.name!r}")
                if member.issym() or member.islnk() or not (member.isdir() or member.isfile()):
                    raise StaticSiteError(
                        f"unsupported entry in generated bundle: {member.name!r}")
                destination = stage.joinpath(*relative.parts)
                if member.isdir():
                    destination.mkdir(parents=True, exist_ok=True)
                    continue
                source = packed.extractfile(member)
                if source is None:
                    raise StaticSiteError(f"cannot read generated bundle entry: {member.name!r}")
                destination.parent.mkdir(parents=True, exist_ok=True)
                with source, destination.open("wb") as output:
                    shutil.copyfileobj(source, output)

        for required in ("index.html", "agent-manifest.json"):
            if not (stage / required).is_file():
                raise StaticSiteError(f"generated bundle is missing {required}")

        if target.exists():
            target.replace(backup)
        stage.replace(target)
        if backup.exists():
            shutil.rmtree(backup)
    except Exception:
        if stage.exists():
            shutil.rmtree(stage, ignore_errors=True)
        if backup.exists() and not target.exists():
            backup.replace(target)
        raise


def public_file(root: Path, relative: str) -> Path | None:
    """Resolve one browser path below ``root`` without allowing traversal."""
    root = Path(root).resolve()
    candidate = (root / (relative or "index.html")).resolve()
    try:
        candidate.relative_to(root)
    except ValueError:
        return None
    if candidate.is_dir():
        candidate = candidate / "index.html"
    return candidate if candidate.is_file() else None

